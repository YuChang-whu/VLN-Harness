#!/usr/bin/env python3
"""Analyze StreamVLN model actions against Habitat shortest-path expert actions.

This script expects episode_logs generated by streamvln_eval.py with
--record_oracle_actions. It does not rerun Habitat or the model.
"""

import argparse
import json
import math
import os
from collections import Counter, defaultdict

ACTION_NAMES = {
    0: "STOP",
    1: "MOVE_FORWARD",
    2: "TURN_LEFT",
    3: "TURN_RIGHT",
}

MANUAL_REVIEW = "未覆盖/需人工复核"


def as_float(value):
    try:
        value = float(value)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(value):
        return None
    return value


def load_results(output_dir):
    path = os.path.join(output_dir, "result.json")
    rows = []
    if not os.path.exists(path):
        raise SystemExit(f"No result.json found: {path}")
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if "scene_id" in row and "episode_id" in row:
                rows.append(row)
    return rows


def load_episode_log(result, output_dir):
    candidates = []
    log_path = result.get("episode_log")
    if log_path:
        candidates.append(log_path)
        candidates.append(os.path.join(output_dir, log_path))
    log_dir = os.path.join(output_dir, "episode_logs")
    if os.path.isdir(log_dir):
        suffix = f"_{result.get('scene_id')}_{result.get('episode_id')}.json"
        candidates.extend(
            os.path.join(log_dir, name)
            for name in os.listdir(log_dir)
            if name.endswith(suffix)
        )
    for candidate in candidates:
        if candidate and os.path.exists(candidate):
            with open(candidate, "r") as f:
                return json.load(f), candidate
    return None, None


def get_metric(step, metric_name, source="pre_metrics"):
    metrics = step.get(source) or {}
    return as_float(metrics.get(metric_name))


def get_collision(step):
    metrics = step.get("post_metrics") or step.get("pre_metrics") or {}
    collisions = metrics.get("collisions")
    if isinstance(collisions, dict):
        if collisions.get("is_collision") is not None:
            return bool(collisions.get("is_collision"))
        if collisions.get("count") is not None:
            return int(collisions.get("count") or 0) > 0
    return False


def normalize_step(step):
    model_action = step.get("model_action", step.get("action"))
    oracle_action = step.get("oracle_action")
    try:
        model_action = int(model_action) if model_action is not None else None
    except Exception:
        model_action = None
    try:
        oracle_action = int(oracle_action) if oracle_action is not None else None
    except Exception:
        oracle_action = None
    return {
        "step": step.get("step_id"),
        "model_action": model_action,
        "model_action_name": step.get("model_action_name") or step.get("action_name") or ACTION_NAMES.get(model_action),
        "oracle_action": oracle_action,
        "oracle_action_name": step.get("oracle_action_name") or ACTION_NAMES.get(oracle_action),
        "distance_to_goal": get_metric(step, "distance_to_goal", "pre_metrics"),
        "post_distance_to_goal": get_metric(step, "distance_to_goal", "post_metrics"),
        "success": get_metric(step, "success", "post_metrics"),
        "collision": get_collision(step),
        "oracle_error": step.get("oracle_error"),
        "model_matches_oracle": (model_action is not None and oracle_action is not None and model_action == oracle_action),
    }


def mismatch(step):
    return step["model_action"] is not None and step["oracle_action"] is not None and step["model_action"] != step["oracle_action"]


def find_first_divergence(steps, min_consecutive_mismatch=2):
    mismatches = [mismatch(step) for step in steps]
    if not any(mismatches):
        return None
    window = max(1, int(min_consecutive_mismatch))
    if window > 1:
        for idx in range(0, len(steps) - window + 1):
            if all(mismatches[idx:idx + window]):
                return steps[idx]
    return steps[mismatches.index(True)]


def count_opposite_turns(steps):
    return sum(
        1
        for step in steps
        if (step["model_action"], step["oracle_action"]) in {(2, 3), (3, 2)}
    )


def max_consecutive_model_forward_when_oracle_turns(steps):
    best = 0
    cur = 0
    for step in steps:
        if step["model_action"] == 1 and step["oracle_action"] in {2, 3}:
            cur += 1
            best = max(best, cur)
        else:
            cur = 0
    return best


def classify_divergence(first, steps, result):
    if not steps:
        return "缺少 expert action 日志"
    if first is None:
        return "模型动作与 shortest-path expert 基本一致"

    step_id = int(first.get("step") or 0)
    model = first.get("model_action")
    oracle = first.get("oracle_action")
    opposite_turns = count_opposite_turns(steps)
    forward_against_turn = max_consecutive_model_forward_when_oracle_turns(steps)

    if oracle == 0 and model != 0:
        return "oracle 要 STOP，模型继续走：STOP calibration 问题"
    if opposite_turns >= 3:
        return "模型动作和 oracle 经常相反：动作语义接口或训练分布问题"
    if oracle in {2, 3} and model == 1 and forward_against_turn >= 2:
        return "oracle 要转，模型持续 MOVE_FORWARD：局部避障/几何反馈问题"
    if step_id <= 5:
        return "第 0-5 步就偏：初始朝向 / prompt grounding 问题"
    if step_id > 5:
        return "中途 landmark 后偏：子目标切换 / 长程语言理解问题"
    return MANUAL_REVIEW


def confusion_key(step):
    return f"M:{step['model_action_name']} / O:{step['oracle_action_name']}"


def analyze_episode(result, log, log_path, min_consecutive_mismatch):
    raw_steps = log.get("steps", []) if log else []
    steps = [normalize_step(step) for step in raw_steps]
    oracle_steps = [step for step in steps if step["oracle_action"] is not None]
    first = find_first_divergence(oracle_steps, min_consecutive_mismatch)
    divergence_type = classify_divergence(first, oracle_steps, result)
    mismatched = [step for step in oracle_steps if mismatch(step)]
    confusion = Counter(confusion_key(step) for step in mismatched)
    model_counts = Counter(step["model_action_name"] for step in oracle_steps)
    oracle_counts = Counter(step["oracle_action_name"] for step in oracle_steps)

    return {
        "episode_index": log.get("episode_index") if log else None,
        "scene_id": result.get("scene_id"),
        "episode_id": result.get("episode_id"),
        "instruction": result.get("episode_instruction", ""),
        "success": as_float(result.get("success")),
        "spl": as_float(result.get("spl")),
        "os": as_float(result.get("os")),
        "ne": as_float(result.get("ne")),
        "steps": result.get("steps", len(steps)),
        "video_file": result.get("video_file"),
        "episode_log": log_path or result.get("episode_log"),
        "has_oracle_actions": bool(oracle_steps),
        "oracle_action_steps": len(oracle_steps),
        "mismatch_count": len(mismatched),
        "mismatch_rate": len(mismatched) / len(oracle_steps) if oracle_steps else None,
        "first_divergence_step": first.get("step") if first else None,
        "first_divergence": first,
        "first_divergence_type": divergence_type,
        "opposite_turn_count": count_opposite_turns(oracle_steps),
        "max_forward_against_oracle_turn": max_consecutive_model_forward_when_oracle_turns(oracle_steps),
        "oracle_stop_model_continue_count": sum(1 for step in oracle_steps if step["oracle_action"] == 0 and step["model_action"] != 0),
        "model_counts": dict(model_counts),
        "oracle_counts": dict(oracle_counts),
        "top_confusions": confusion.most_common(10),
    }


def fmt(value, digits=3):
    value = as_float(value)
    if value is None:
        return "NA"
    return f"{value:.{digits}f}"


def build_reports(output_dir, min_consecutive_mismatch, include_successes, max_examples):
    results = load_results(output_dir)
    details = []
    missing_logs = []
    for result in results:
        log, log_path = load_episode_log(result, output_dir)
        if log is None:
            missing_logs.append(f"{result.get('scene_id')}_{result.get('episode_id')}")
            log = {}
        details.append(analyze_episode(result, log, log_path, min_consecutive_mismatch))

    failures = [item for item in details if as_float(item.get("success")) != 1.0]
    successes = [item for item in details if as_float(item.get("success")) == 1.0]
    report_items = details if include_successes else failures
    type_counter = Counter(item["first_divergence_type"] for item in report_items)
    failure_type_counter = Counter(item["first_divergence_type"] for item in failures)
    success_type_counter = Counter(item["first_divergence_type"] for item in successes)
    confusion_counter = Counter()
    for item in report_items:
        for key, count in item.get("top_confusions", []):
            confusion_counter[key] += count

    json_path = os.path.join(output_dir, "oracle_action_alignment.json")
    with open(json_path, "w") as f:
        json.dump(
            {
                "output_dir": output_dir,
                "min_consecutive_mismatch": min_consecutive_mismatch,
                "total_episodes": len(details),
                "failure_count": len(failures),
                "success_count": len(successes),
                "missing_logs": missing_logs,
                "details": details,
            },
            f,
            indent=2,
            ensure_ascii=False,
        )

    md_path = os.path.join(output_dir, "oracle_action_alignment_report.md")
    with open(md_path, "w") as f:
        f.write("# Oracle Action / Expert Action 对齐报告\n\n")
        f.write(f"- 评估目录：`{output_dir}`\n")
        f.write(f"- 总 episode：{len(details)}\n")
        f.write(f"- 成功 episode：{len(successes)}\n")
        f.write(f"- 失败 episode：{len(failures)}\n")
        f.write(f"- first divergence 判定：连续 mismatch >= {min_consecutive_mismatch} 优先，否则退回第一个 mismatch\n")
        f.write(f"- 缺少日志 episode：{len(missing_logs)}\n\n")

        f.write("## 1. 失败 episode 的 first divergence 类型\n\n")
        for name, count in failure_type_counter.most_common():
            f.write(f"- {name}: {count}\n")
        if not failure_type_counter:
            f.write("- 无失败 episode 或无可统计数据\n")
        f.write("\n")

        f.write("## 2. 成功 episode 的对照分布\n\n")
        for name, count in success_type_counter.most_common():
            f.write(f"- {name}: {count}\n")
        if not success_type_counter:
            f.write("- 无成功 episode 或无可统计数据\n")
        f.write("\n")

        f.write("## 3. 高频 model/oracle 动作混淆\n\n")
        for name, count in confusion_counter.most_common(20):
            f.write(f"- {name}: {count}\n")
        if not confusion_counter:
            f.write("- 未发现动作不一致，或日志没有 oracle action\n")
        f.write("\n")

        f.write("## 4. 失败样例明细\n\n")
        sorted_failures = sorted(
            failures,
            key=lambda item: (
                item["first_divergence_step"] is None,
                item["first_divergence_step"] if item["first_divergence_step"] is not None else 10**9,
                -(item["ne"] or 0),
            ),
        )
        for item in sorted_failures[:max_examples]:
            first = item.get("first_divergence") or {}
            f.write(
                f"- #{item.get('episode_index')} {item['scene_id']}_{item['episode_id']} "
                f"NE={fmt(item.get('ne'))} SPL={fmt(item.get('spl'))} "
                f"first_step={item.get('first_divergence_step')} "
                f"type={item.get('first_divergence_type')} "
                f"model={first.get('model_action_name')} oracle={first.get('oracle_action_name')} "
                f"dist={fmt(first.get('distance_to_goal'))} "
                f"log=`{item.get('episode_log')}`\n"
            )
        if len(sorted_failures) > max_examples:
            f.write(f"\n仅展示前 {max_examples} 条，完整明细见 `{json_path}`。\n")
        f.write("\n")

        f.write("## 5. 如何解读\n\n")
        f.write("- 第 0-5 步就偏：优先人工看初始朝向、首帧视觉、prompt 是否让模型选错方向。\n")
        f.write("- 中途 landmark 后偏：优先检查语言子目标切换和长程记忆是否丢失。\n")
        f.write("- oracle 要转，模型持续 MOVE_FORWARD：优先检查局部几何反馈、碰撞恢复、深度/位姿输入利用。\n")
        f.write("- oracle 要 STOP，模型继续走：对应 STOP calibration，可和 Oracle STOP Replay 互相验证。\n")
        f.write("- 模型和 oracle 经常相反：优先排查动作语义编号、左右转定义、训练动作分布。\n")
        f.write(f"- {MANUAL_REVIEW}：自动规则暂时不能解释，需要结合视频、top-down map、原始 prompt 人工复核。\n")

    return json_path, md_path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output_dir", required=True)
    parser.add_argument("--min_consecutive_mismatch", type=int, default=2)
    parser.add_argument("--include_successes", action="store_true", help="Build aggregate confusion stats on all episodes instead of failures only")
    parser.add_argument("--max_examples", type=int, default=120)
    args = parser.parse_args()
    json_path, md_path = build_reports(
        args.output_dir,
        args.min_consecutive_mismatch,
        args.include_successes,
        args.max_examples,
    )
    print(f"Wrote {json_path}")
    print(f"Wrote {md_path}")


if __name__ == "__main__":
    main()
